-- Multi-Unit Inspections (Stage 1) — first-class units/scopes under one inspection.
--
-- A job can hold multiple UNITS plus COMMON AREAS. Each finding, checklist
-- selection, limitation, reference photo, and equipment row optionally belongs
-- to a unit via a nullable `unit_id`. unit_id IS NULL means "no unit" — which is
-- every existing inspection and every single-family job, so legacy data and the
-- whole single-family flow render exactly as before (no backfill needed).
--
-- Idempotent — safe to re-run. Run in the Supabase SQL Editor.

-- 1) The units table. One row per unit; Common Areas is a row with
--    is_common_area = true. Mirrors the per-inspection RLS used by
--    report_section_overrides / report_section_notes.
create table if not exists public.inspection_units (
  id bigint generated by default as identity primary key,
  inspection_id bigint not null references public.inspections(id) on delete cascade,
  label text not null,
  sort_order integer not null default 0,
  is_common_area boolean not null default false,
  created_at timestamptz not null default now()
);

create index if not exists inspection_units_inspection_id_idx
  on public.inspection_units (inspection_id);

alter table public.inspection_units enable row level security;

drop policy if exists "Inspectors manage own inspection units" on public.inspection_units;
create policy "Inspectors manage own inspection units"
on public.inspection_units
for all
to authenticated
using (
  exists (
    select 1 from public.inspections
    where inspections.id = inspection_units.inspection_id
    and inspections.inspector_id = auth.uid()
  )
)
with check (
  exists (
    select 1 from public.inspections
    where inspections.id = inspection_units.inspection_id
    and inspections.inspector_id = auth.uid()
  )
);

drop policy if exists "Inspection units on published inspections are publicly readable" on public.inspection_units;
create policy "Inspection units on published inspections are publicly readable"
on public.inspection_units
for select
to anon, authenticated
using (
  exists (
    select 1 from public.inspections
    where inspections.id = inspection_units.inspection_id
    and inspections.published = true
  )
);

-- 2) Nullable unit_id on every per-scope child table. ON DELETE SET NULL so
--    deleting a unit never deletes its findings — they fall back to "no unit".
alter table public.findings
  add column if not exists unit_id bigint references public.inspection_units(id) on delete set null;
create index if not exists findings_unit_id_idx on public.findings (unit_id);

alter table public.section_checklist_selections
  add column if not exists unit_id bigint references public.inspection_units(id) on delete set null;
create index if not exists section_checklist_selections_unit_id_idx on public.section_checklist_selections (unit_id);

alter table public.section_limitations
  add column if not exists unit_id bigint references public.inspection_units(id) on delete set null;
create index if not exists section_limitations_unit_id_idx on public.section_limitations (unit_id);

alter table public.section_reference_photos
  add column if not exists unit_id bigint references public.inspection_units(id) on delete set null;
create index if not exists section_reference_photos_unit_id_idx on public.section_reference_photos (unit_id);

alter table public.equipment_inventory
  add column if not exists unit_id bigint references public.inspection_units(id) on delete set null;
create index if not exists equipment_inventory_unit_id_idx on public.equipment_inventory (unit_id);

-- report_section_overrides / report_section_notes: column added for future
-- per-unit custom sections/notes. Stage 1 keeps these inspection-level
-- (unit_id NULL / shared across units), so their existing
-- unique(inspection_id, section_name) constraints are intentionally left as-is.
alter table public.report_section_overrides
  add column if not exists unit_id bigint references public.inspection_units(id) on delete set null;

alter table public.report_section_notes
  add column if not exists unit_id bigint references public.inspection_units(id) on delete set null;

-- 3) Convenience/source-of-truth columns on inspections (drives UI + future
--    base + per-unit pricing). The inspection_units rows remain authoritative.
alter table public.inspections
  add column if not exists is_multi_unit boolean not null default false;
alter table public.inspections
  add column if not exists unit_count integer not null default 1;
alter table public.inspections
  add column if not exists unit_naming text; -- 'numeric' (1/2/3) | 'alpha' (A/B/C)
